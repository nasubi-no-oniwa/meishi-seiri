// ランキングのルールの試験（GitHub の上で Firebase の試し用データベースを立てて試す。本番のデータには触らない）
const NS='ft-green-default-rtdb',PROJ='ft-green',BASE='http://127.0.0.1:9000';
const b64=o=>Buffer.from(JSON.stringify(o)).toString('base64url');
const tok=uid=>b64({alg:'none',typ:'JWT'})+'.'+b64({uid,sub:uid,user_id:uid,iat:Math.floor(Date.now()/1000),exp:Math.floor(Date.now()/1000)+3600,aud:PROJ,iss:'https://securetoken.google.com/'+PROJ,provider_id:'anonymous',firebase:{sign_in_provider:'anonymous'}})+'.';
async function req(method,path,uid,body){const r=await fetch(BASE+'/'+path+'.json?ns='+NS+(uid?'&auth='+tok(uid):''),{method,headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return {ok:r.ok,status:r.status,j:await r.json().catch(()=>null)};}
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
let fail=0;const ex=(name,res,want)=>{const ok=res.ok===want;console.log((ok?'OK  ':'NG  ')+name+' → '+res.status);if(!ok){fail++;console.log(JSON.stringify(res.j));}};
const TS={'.sv':'timestamp'};
const U='user1aaaaaaaaaaaaaaaaaaa',U2='user2bbbbbbbbbbbbbbbbbbb';
const P='meishi/';
async function ticket(uid){const r=await req('PUT',P+'runs/'+uid,uid,{t:TS});const g=await req('GET',P+'runs/'+uid,uid);return {r,st:g.j&&g.j.t};}
const K=(s,m)=>s*1000+999-m;
const rec=(st,s,m=0,n='テスト')=>({n,s,m,k:K(s,m),st,v:1,t:TS});
const dk=()=>Math.floor((Date.now()+32400000)/86400000);
const recD=(st,s,m=0,n='テスト')=>({...rec(st,s,m,n),dk:dk(),ds:dk()*10000000+K(s,m)});
ex('ログインなしで始める',await req('PUT',P+'runs/'+U,null,{t:TS}),false);
let tk=await ticket(U);ex('始めた時刻を書く',tk.r,true);
const tk2=await ticket(U2);
ex('ほかの人の場所に書く',await req('PUT',P+'runs/'+U,U2,{t:TS}),false);
ex('始めてすぐに記録を送る（60秒たっていない）',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30)),false);
console.log('56秒待ちます');await sleep(56000);
ex('始めた時刻がちがう記録',await req('PUT',P+'all/scores/'+U,U,rec(tk.st-5000,10)),false);
ex('0枚の記録',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,0)),false);
ex('枚数が多すぎる（241枚）',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,241)),false);
ex('k がおかしい',await req('PUT',P+'all/scores/'+U,U,{...rec(tk.st,30,1),k:K(30,0)}),false);
ex('ふつうの記録（30枚・まちがい2）',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,2)),true);
ex('今日のランキングに、ds がおかしい記録',await req('PUT',P+'d/scores/'+U,U,{...recD(tk.st,30,2),ds:dk()*10000000+K(31,2)}),false);
ex('今日のランキングに書く',await req('PUT',P+'d/scores/'+U,U,recD(tk.st,30,2)),true);
ex('同じ回でもう一度送る（まちがいを減らす）',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,1)),false);
ex('名前だけ変える',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,2,'なまえ')),true);
ex('今日のほうも名前だけ変える',await req('PUT',P+'d/scores/'+U,U,recD(tk.st,30,2,'なまえ')),true);
ex('名前を変えるふりで枚数を変える',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,31,2,'なまえ2')),false);
ex('13文字の名前',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,2,'あいうえおかきくけこさしす')),false);
ex('今日のランキングに、ちがう日で書く',await req('PUT',P+'d/scores/'+U2,U2,{...rec(tk2.st,10),dk:dk()-1,ds:(dk()-1)*10000000+K(10,0)}),false);
tk=await ticket(U);console.log('56秒待ちます');await sleep(56000);
ex('前より悪い記録は全期間に載らない',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,3)),false);
ex('同じ枚数でまちがいが少なければ全期間に載る',await req('PUT',P+'all/scores/'+U,U,rec(tk.st,30,0)),true);
ex('今日のほうも同じ枚数でまちがいが少なければ載る',await req('PUT',P+'d/scores/'+U,U,recD(tk.st,30,0)),true);
ex('名刺入れごとシュレッダー',await req('PUT',P+'zen/'+U,U,{t:TS}),true);
ex('すぐにもう一度',await req('PUT',P+'zen/'+U,U,{t:TS}),false);
ex('ほかの人の分を書く',await req('PUT',P+'zen/'+U2,U,{t:TS}),false);
ex('だれでもランキングを読める',await req('GET',P+'all/scores',null),true);
ex('だれでも今日のランキングを読める',await req('GET',P+'d/scores',null),true);
ex('地位を失った人の数を読める',await req('GET',P+'zen',null),true);
ex('ほかの人の始めた時刻は読めない',await req('GET',P+'runs/'+U,U2),false);
ex('hidden に書く',await req('PUT',P+'hidden/'+U,U,true),false);
ex('ほかのゲームの場所に書く',await req('PUT','hitsujikai/oji/'+U,U,{t:TS}),false);
console.log(fail?('失敗 '+fail+' 件'):'すべて合格');
if(fail)process.exit(1);
